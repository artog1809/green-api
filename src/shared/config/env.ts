/**
 * Базовый адрес API. У каждого инстанса GREEN-API он свой (указан в личном
 * кабинете), поэтому значение переопределяется переменной окружения.
 */
// Именно `||`, а не `??`: на хостинге переменная, объявленная без значения,
// приходит пустой строкой, и `??` пропустил бы её дальше как валидную.
export const DEFAULT_API_URL =
  import.meta.env.VITE_GREEN_API_URL?.trim() || 'https://api.green-api.com'

/**
 * Сколько секунд сервер держит соединение в ожидании нового уведомления.
 * Допустимый диапазон по документации GREEN-API — 5..60.
 */
export const RECEIVE_TIMEOUT_SECONDS = 20

/**
 * Минимальный интервал между запросами к очереди уведомлений.
 * receiveTimeout — просьба к серверу подождать, а не гарантия: шлюз GREEN-API
 * может ответить пустым телом сразу же. Пауза ограничивает частоту запросов,
 * а когда уведомление пришло, следующий запрос уходит без задержки —
 * очередь разбирается на полной скорости.
 */
export const MIN_POLL_INTERVAL_MS = 5000

/** Сколько сообщений истории запрашиваем при открытии чата. */
export const CHAT_HISTORY_COUNT = 100
